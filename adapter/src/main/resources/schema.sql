CREATE TABLE UTENTE (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 5000) PRIMARY KEY,
    NOMEUTENTE VARCHAR(50) NOT NULL UNIQUE,
    NOME VARCHAR(50) NOT NULL,
    COGNOME VARCHAR(50) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL
);

CREATE TABLE RUOLO (
    ID INTEGER PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    DESCRIZIONE VARCHAR(255) NOT NULL
);

CREATE TABLE UTENTE_RUOLO (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 5000) PRIMARY KEY,
    IDUTENTE BIGINT NOT NULL,
    IDRUOLO BIGINT NOT NULL,
    CONSTRAINT FK_UR_UTENTE FOREIGN KEY (IDUTENTE) REFERENCES UTENTE(ID),
    CONSTRAINT FK_UR_RUOLO FOREIGN KEY (IDRUOLO) REFERENCES RUOLO(ID),
    CONSTRAINT UK_UR UNIQUE (IDUTENTE, IDRUOLO)
);